%% ------------------------- local functions -------------------------
function mu = masetti(N, dop)
% Masetti et al. 1983 doping-dependent low-field mobility (cm^2/Vs)
switch dop
    case 'P'   % phosphorus (n)
        mu = 68.5 + (1414-68.5)./(1+(N/9.20e16).^0.711) - 56.1./(1+(3.41e20./N).^1.98);
    case 'As'  % arsenic (n)
        mu = 52.2 + (1417-52.2)./(1+(N/9.68e16).^0.680) - 43.4./(1+(3.43e20./N).^2.00);
    case 'B'   % boron (p)
        mu = 44.9*exp(-9.23e16./N) + 470.5./(1+(N/2.23e17).^0.719) - 29.0./(1+(6.10e20./N).^2.00);
end
end

function [vth, gmmax] = vth_maxgm(vg, id, isP, vds)
% Linear-extrapolation Vth at maximum transconductance, linear region.
% For PMOS the curve is mirrored so the same code applies; vth gets re-mirrored.
if isP, vg = -vg; id = -id; end
gm = gradient(id, vg);                 % central differences
[gmmax, im] = max(gm);
vth = vg(im) - id(im)/gmmax - vds/2;   % -VDS/2: linear-region correction
if isP, vth = -vth; end
end
