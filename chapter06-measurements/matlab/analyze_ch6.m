%% ET4ICP Chapter 6 — Measurement analysis for Group 9
%  Computes:
%   1. Van der Pauw sheet resistances + doping concentrations (Irvin/Masetti)
%   2. ELM sheet resistances + lateral out-diffusion
%   3. NMOS/PMOS Vth + mobility from Id-Vg (max-gm linear extrapolation)
%   4. Vth vs V_T-adjust dose (quadrant sweep) vs Sentaurus simulations
%   5. Id-Vds output characteristics + channel-length modulation
%  All figures land in ../figures, parameters in ../extracted_parameters.txt
clear; close all; clc;

root   = fileparts(mfilename('fullpath'));          % .../chapter06-measurements/matlab
dataD  = fullfile(root, '..', 'IC', 'Group 9');
figD   = fullfile(root, '..', 'figures');
if ~exist(figD, 'dir'), mkdir(figD); end
outTxt = fullfile(root, '..', 'extracted_parameters.txt');
fid    = fopen(outTxt, 'w');
logf   = @(varargin) cellfun(@(t) fprintf(t, varargin{:}), {1, fid}, 'UniformOutput', false);

K    = pi/log(2);          % VdP correction factor
q    = 1.602176634e-19;    % C
Cox  = 8.8541878128e-12*3.9/100e-9;   % F/m^2 (tox = 100 nm)  = 3.453e-4
CoxC = Cox*1e-4;                       % F/cm^2 = 3.453e-8

% Junction depths from Chapter 3 Sentaurus sims (device_sims/junction_depths.txt)
xj.NW = 2.085e-4;  % cm
xj.SN = 0.537e-4;
xj.SP = 0.594e-4;
% Chapter 4 in-line four-point-probe references (Ω/sq)
ch4.NW = 1488.8; ch4.SN = 57.4; ch4.SP = 510.6;

logf('=========================================================\n');
logf('ET4ICP Chapter 6 analysis — Group 9   (generated by analyze_ch6.m)\n');
logf('=========================================================\n\n');

%% ------------------------------------------------------------------
%  1. VAN DER PAUW
%  R_AB,CD = slope of (V1-V2) vs Iforce;  Rsq = pi/ln2 * R_AB,CD
% -------------------------------------------------------------------
vdp = struct('name', {'NW','SN','SP','IC'}, ...
             'file', {'NW_VDP.csv','SN_VDP.csv','SP_NW_VDP.csv','IC_VDP.csv'});
figure('Visible','off','Position',[0 0 1000 750]);
tl = tiledlayout(2,2,'TileSpacing','compact','Padding','compact');
logf('--- 1. Van der Pauw sheet resistances ---\n');
logf('%-6s %14s %14s %12s\n','layer','R_AB,CD (Ohm)','Rsq (Ohm/sq)','fit R^2');
for k = 1:numel(vdp)
    T  = readtable(fullfile(dataD, vdp(k).file));
    dV = T.V1 - T.V2;  I = T.Iforce;
    p  = polyfit(I, dV, 1);
    Rk = p(1);  Rsq = K*Rk;
    res = dV - polyval(p, I);  r2 = 1 - sum(res.^2)/sum((dV-mean(dV)).^2);
    vdp(k).R = Rk; vdp(k).Rsq = Rsq;
    logf('%-6s %14.4f %14.4f %12.6f\n', vdp(k).name, Rk, Rsq, r2);

    nexttile; plot(I*1e6, dV*1e3, 'o', 'MarkerSize', 4); hold on;
    plot(I*1e6, polyval(p, I)*1e3, 'r-', 'LineWidth', 1.2);
    grid on; xlabel('I_{force} (\muA)'); ylabel('V_1 - V_2 (mV)');
    title(sprintf('%s :  R_{AB,CD} = %.4g \\Omega \\rightarrow R_{sq} = %.4g \\Omega/sq', ...
          vdp(k).name, Rk, Rsq));
end
title(tl, 'Van der Pauw structures — 4-point I/V and linear fits (Group 9, TL quadrant)');
exportgraphics(gcf, fullfile(figD,'vdp_iv_fits.png'), 'Resolution', 180);

% --- Doping concentration via rho = Rsq*xj and Masetti mobility (Irvin) ---
logf('\n--- 1b. Doping concentrations (rho = Rsq*xj, Masetti mobility) ---\n');
logf('%-6s %10s %12s %14s %16s %12s\n','layer','xj (um)','rho (Ohm.cm)','mu (cm^2/Vs)','N (cm^-3)','Ch4 N');
layers = {'NW','P' ; 'SN','As' ; 'SP','B'};
ch4N   = [1.5e16, 2e19, 1.5e18];
for k = 1:size(layers,1)
    nm  = layers{k,1};  dop = layers{k,2};
    Rs  = vdp(strcmp({vdp.name}, nm)).Rsq;
    rho = Rs * xj.(nm);                       % Ohm.cm
    f   = @(lgN) rho - 1./(q .* masetti(10.^lgN, dop) .* 10.^lgN);
    lgN = fzero(f, [14 21]);
    N   = 10^lgN;  mu = masetti(N, dop);
    doping.(nm) = N;
    logf('%-6s %10.3f %12.4g %14.1f %16.3g %12.3g\n', nm, xj.(nm)*1e4, rho, mu, N, ch4N(k));
end
% metal sanity check
RsIC = vdp(strcmp({vdp.name},'IC')).Rsq;
logf('IC metal: Rsq = %.4f Ohm/sq -> rho = Rsq*d = %.3g Ohm.cm (d = 0.2 um Al/1%%Si, lit. ~2.7-3.2e-6)\n', ...
     RsIC, RsIC*0.2e-4);

%% ------------------------------------------------------------------
%  2. ELM — electrical line width
%  R from (VH-VL) vs Iforce.  L = 206 um.  Apparent Rsq = R*W/L.
%  Conductance fit: 1/R = (W + 2*dW)/(Rsq*L)  ->  slope & x-intercept
% -------------------------------------------------------------------
L_elm = 206;                       % um
Ws    = [2 5 10];                  % drawn widths, um
lays  = {'NW','SN'};
logf('\n--- 2. ELM structures (L = 206 um) ---\n');
logf('%-4s %6s %14s %18s\n','lay','W(um)','R (Ohm)','Rsq,app (Ohm/sq)');
Rel = struct();
for il = 1:2
    lay = lays{il};
    for iw = 1:3
        T  = readtable(fullfile(dataD, sprintf('ELM_%s_%dum.csv', lay, Ws(iw))));
        dV = T.VH - T.VL;  I = T.Iforce;
        p  = polyfit(I, dV, 1);
        Rel.(lay)(iw) = p(1);
        logf('%-4s %6d %14.2f %18.3f\n', lay, Ws(iw), p(1), p(1)*Ws(iw)/L_elm);
    end
end

% conductance fit -> Rsq_ELM and lateral out-diffusion dW
logf('\n%-4s %16s %14s %12s\n','lay','Rsq_ELM (Ohm/sq)','dW (um)','fit R^2');
figure('Visible','off','Position',[0 0 1100 420]);
tiledlayout(1,2,'TileSpacing','compact','Padding','compact');
for il = 1:2
    lay = lays{il};
    G   = 1./Rel.(lay);
    p   = polyfit(Ws, G, 1);
    RsqE = 1/(p(1)*L_elm);
    dW   = p(2)/(2*p(1));
    res  = G - polyval(p,Ws); r2 = 1 - sum(res.^2)/sum((G-mean(G)).^2);
    elm.(lay).Rsq = RsqE;  elm.(lay).dW = dW;
    logf('%-4s %16.2f %14.3f %12.6f\n', lay, RsqE, dW, r2);

    nexttile;
    Wfit = linspace(-2*dW-0.5, 11, 100);
    plot(Ws, G*1e3, 'bo', 'MarkerSize', 7, 'LineWidth', 1.4); hold on;
    plot(Wfit, polyval(p,Wfit)*1e3, 'r-', 'LineWidth', 1.2);
    xline(-2*dW, 'k--'); yline(0, 'k-');
    text(-2*dW, max(G*1e3)*0.45, sprintf('  -2\\DeltaW = %.2f \\mum', -2*dW), 'Rotation', 90);
    grid on; xlabel('drawn width W (\mum)'); ylabel('conductance 1/R (mS)');
    title(sprintf('%s :  R_{sq} = %.1f \\Omega/sq,  \\DeltaW = %.2f \\mum', lay, RsqE, dW));
end
sgtitle('ELM conductance vs drawn width — lateral out-diffusion extraction');
exportgraphics(gcf, fullfile(figD,'elm_deltaW_fit.png'), 'Resolution', 180);

% apparent Rsq vs width with VdP reference
figure('Visible','off','Position',[0 0 1100 420]);
tiledlayout(1,2,'TileSpacing','compact','Padding','compact');
for il = 1:2
    lay  = lays{il};
    RsV  = vdp(strcmp({vdp.name}, lay)).Rsq;
    Rapp = Rel.(lay).*Ws/L_elm;
    Rcor = Rel.(lay).*(Ws + 2*elm.(lay).dW)/L_elm;
    nexttile;
    plot(Ws, Rapp, 'bo-', 'LineWidth', 1.4, 'MarkerSize', 7); hold on;
    plot(Ws, Rcor, 'ms-', 'LineWidth', 1.2, 'MarkerSize', 7);
    yline(RsV, 'r--', sprintf('VdP  %.1f \\Omega/sq', RsV), 'LineWidth', 1.2);
    grid on; xlabel('drawn width W (\mum)'); ylabel('R_{sq} (\Omega/sq)');
    legend('apparent  R\cdotW_{drawn}/L', 'corrected  R\cdot(W+2\DeltaW)/L', 'Location','southeast');
    title(sprintf('%s sheet resistance vs line width', lay));
end
sgtitle('ELM apparent sheet resistance — effect of lateral out-diffusion');
exportgraphics(gcf, fullfile(figD,'elm_rsq_vs_width.png'), 'Resolution', 180);

